param(
    [string]$SourceDir
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repository = Split-Path -Parent $PSScriptRoot
$target = Join-Path $repository 'connectors'
if ([string]::IsNullOrWhiteSpace($SourceDir)) {
    $SourceDir = Join-Path ([IO.Path]::GetTempPath()) ('powerbi-packages-' + [Guid]::NewGuid().ToString('N'))
    & (Join-Path $PSScriptRoot 'download_connectors.ps1') -TargetDir $SourceDir
}
if (-not (Test-Path -LiteralPath $SourceDir -PathType Container)) {
    throw "Package folder not found: $SourceDir. Supply -SourceDir with a folder containing .mez or .pqx packages."
}
$source = (Resolve-Path -LiteralPath $SourceDir).Path
if ($source.Equals($target, [StringComparison]::OrdinalIgnoreCase) -or
    $source.StartsWith($target + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'SourceDir must be outside connectors/.'
}
$packages = @(Get-ChildItem -LiteralPath $source -File -Recurse |
    Where-Object { $_.Extension -in '.mez', '.pqx' } | Sort-Object FullName)
if ($packages.Count -eq 0) {
    throw "No .mez or .pqx packages found in $source. Existing connectors were preserved."
}
$duplicates = @($packages | Group-Object BaseName | Where-Object Count -gt 1)
if ($duplicates.Count -gt 0) {
    throw "Duplicate connector names: $($duplicates.Name -join ', '). Supply a folder containing one package per connector."
}

Add-Type -AssemblyName System.IO.Compression.FileSystem
$stage = Join-Path $repository ('.refresh-' + [Guid]::NewGuid().ToString('N'))
$backup = Join-Path $stage 'previous'
$prepared = Join-Path $stage 'connectors'
$noise = '.resx', '.png', '.jpg', '.jpeg', '.svg', '.rels', '.xml', '.psdsxs', '.psdor'
New-Item -ItemType Directory -Path $prepared | Out-Null
try {
    $index = @('# Connector index', '', 'Generated by `scripts/refresh_connectors.ps1` from the supplied packages.', '', '| Connector | M source files |', '| --- | ---: |')
    foreach ($package in $packages) {
        $destination = Join-Path $prepared $package.BaseName
        [IO.Compression.ZipFile]::ExtractToDirectory($package.FullName, $destination)
        Get-ChildItem -LiteralPath $destination -File -Recurse |
            Where-Object { $_.Extension -in $noise } |
            Remove-Item -Force
        $sources = @(Get-ChildItem -LiteralPath $destination -File -Recurse |
            Where-Object { $_.Extension -in '.m', '.pq', '.pqm' })
        if ($sources.Count -eq 0) {
            throw "No M source found in $($package.Name). Existing connectors were preserved."
        }
        Get-ChildItem -LiteralPath $destination -Directory -Recurse |
            Sort-Object { $_.FullName.Length } -Descending |
            Where-Object { @(Get-ChildItem -LiteralPath $_.FullName -Force).Count -eq 0 } |
            Remove-Item -Force
        $link = [Uri]::EscapeDataString($package.BaseName)
        $label = $package.BaseName.Replace('|', '&#124;').Replace('[', '&#91;').Replace(']', '&#93;')
        $index += "| [$label]($link/) | $($sources.Count) |"
    }
    Set-Content -LiteralPath (Join-Path $prepared 'README.md') -Value $index -Encoding utf8

    # Keep the previous tree available for rollback until the replacement is installed.
    if (Test-Path -LiteralPath $target) {
        Move-Item -LiteralPath $target -Destination $backup
    }
    try {
        Move-Item -LiteralPath $prepared -Destination $target
    }
    catch {
        if (Test-Path -LiteralPath $backup) {
            Move-Item -LiteralPath $backup -Destination $target
        }
        throw
    }
    Write-Host "Refreshed $($packages.Count) connectors. Index: connectors/README.md"
}
finally {
    # Only remove the unique staging directory created by this invocation.
    if ((Split-Path -Parent $stage) -ne $repository -or (Split-Path -Leaf $stage) -notmatch '^\.refresh-[a-f0-9]{32}$') {
        throw "Unexpected staging path: $stage"
    }
    if ((Test-Path -LiteralPath $backup) -and -not (Test-Path -LiteralPath $target)) {
        Write-Warning "Previous connectors retained at $backup for recovery."
    }
    else {
        Remove-Item -LiteralPath $stage -Recurse -Force
    }
}
